/** あ〜お を1段とする「行」グルーピング（グリッド表示用）。 */
export const AIUEO_ROWS: AiueoEntry[][] = (() => {
  const heads = new Set(['あ', 'か', 'さ', 'た', 'な', 'は', 'ま', 'や', 'ら', 'わ']);
  const rows: AiueoEntry[][] = [];
  for (const e of AIUEO) {
    if (heads.has(e.kana) || rows.length === 0) rows.push([]);
    rows[rows.length - 1].push(e);
  }
  return rows;
})();

/** 誕生日と日付をシードに、毎日1音だけを「きょうのいちもじ」として選ぶ（46日で一周）。 */
export function entryOfTheDay(birthday: string, now: Date = new Date()): AiueoEntry {
  const epochDay = Math.floor(now.getTime() / 86_400_000);
  // 誕生日由来のオフセットで家庭ごとに巡り順をずらす（個人情報はシード値にしか使わない）
  const seed = birthday.split('-').reduce((a, p) => a + Number(p || 0), 0);
  return AIUEO[(epochDay + seed) % AIUEO.length];
}
